import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const theme = JSON.parse(await readFile(new URL('../packages/perse-cua/cursor-theme.json', import.meta.url), 'utf8'))
const point = ([x, y]) => `CGPoint(x: ${x}, y: ${y})`
const list = (items, render) => items.map(render).join(', ')
const color = theme.color.match(/[0-9a-f]{2}/gi).map(hex => parseInt(hex, 16))
const output = `// Generated by scripts/generate-cursor-theme.mjs from cursor-theme.json. Do not edit.
import AppKit

enum CursorTheme {
    static let size: CGFloat = ${theme.size}
    static let viewBox: CGFloat = ${theme.viewBox}
    static let hotspot = ${point(theme.hotspot)}
    static let colorHex = "${theme.color}"
    static let color = NSColor(red: ${color[0]}/255, green: ${color[1]}/255, blue: ${color[2]}/255, alpha: 1)
    static let strokeWidth: CGFloat = ${theme.strokeWidth}
    static let vertices: [(CGPoint, CGPoint, CGPoint)] = [${list(theme.vertices, vertex => `(${list(vertex, point)})`)}]
    static let glow: [(CGFloat, CGFloat)] = [${list(theme.glow, pair => `(${pair.join(', ')})`)}]
    static let clickFPS: Double = ${theme.click.fps}
    static let clickFrames: [(Double, Double)] = [${list(theme.click.frames, pair => `(${pair.join(', ')})`)}]
    static let cueStartScale: Double = ${theme.click.cueStyle.startScale}
    static let cueEndScale: Double = ${theme.click.cueStyle.endScale}
    static let cueFadeInFrames: Double = ${theme.click.cueStyle.fadeInFrames}
    static let cueFadeOutFrames: Double = ${theme.click.cueStyle.fadeOutFrames}
    static let cueOuterWidth: CGFloat = ${theme.click.cueStyle.outerWidth}
    static let cueInnerWidth: CGFloat = ${theme.click.cueStyle.innerWidth}
    static let clickReducedFrame: Double = ${theme.click.cueStyle.reducedFrame}
    static let clickReducedDurationMs: Double = ${theme.click.cueStyle.reducedDurationMs}
    static let clickCue: [(CGPoint, CGPoint)] = [${list(theme.click.cue, pair => `(${list(pair, point)})`)}]
}
`
const path = fileURLToPath(new URL('../packages/perse-cua/native/Sources/CuaNative/CursorTheme.generated.swift', import.meta.url))
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('CursorTheme.generated.swift is stale; run node scripts/generate-cursor-theme.mjs')
} else await writeFile(path, output)
